// Command conformance emits fixtures the control plane test suite asserts
// against.
//
// The agent and the control plane are separate codebases in different
// languages that must agree exactly about the wire. ADR 0002 names that drift
// as the main cost of the split. This closes it for the parts where a
// disagreement would be silent and serious:
//
//   - Enrollment token hashing. If the two sides hash differently, no agent
//     can ever enroll, which at least fails loudly.
//   - Protocol envelope field names. A rename here would mean the control
//     plane silently ignoring messages it does not recognise.
//   - Certificate issuance. The control plane signs certificates the agent
//     must accept, and the agent assigns meaning to the common name.
//
// Run: go run ./cmd/conformance > control-plane/tests/fixtures/conformance.json
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/unharbored/unharbored/internal/deploy"
	"github.com/unharbored/unharbored/internal/enroll"
	"github.com/unharbored/unharbored/internal/protocol"
)

type fixtures struct {
	Note            string          `json:"_note"`
	ProtocolVersion int             `json:"protocol_version"`
	TokenHashes     []tokenHashCase `json:"token_hashes"`
	Envelopes       []envelopeCase  `json:"envelopes"`
	ReleaseIDs      []releaseIDCase `json:"release_ids"`
	Enrollment      enrollmentCase  `json:"enrollment"`
	CommandKinds    []string        `json:"command_kinds"`
	MessageTypes    []string        `json:"message_types"`
	Constants       map[string]any  `json:"constants"`
	ErrorCodes      []string        `json:"error_codes"`
	ResultStatuses  []string        `json:"result_statuses"`
}

type tokenHashCase struct {
	Token string `json:"token"`
	// Hex-encoded SHA-256, which is what the control plane must store.
	SHA256 string `json:"sha256"`
}

type envelopeCase struct {
	Description string          `json:"description"`
	JSON        json.RawMessage `json:"json"`
}

// enrollmentCase pins the encoding of the enrollment exchange, not just its
// field names.
//
// Field names alone were not enough. CSRPEM, CertPEM and CAPEM were once
// []byte, which Go encodes to base64 in JSON while the control plane sent
// plain PEM. Both sides used the agreed field names and the first live
// enrollment still failed, because nothing had ever compared the values.
type enrollmentCase struct {
	// RequestJSON is a complete request as the agent emits it.
	RequestJSON json.RawMessage `json:"request_json"`
	// ResponseJSON is a complete response as the agent expects to parse it.
	ResponseJSON json.RawMessage `json:"response_json"`
	// PemFieldsArePlainText records the decision these fixtures exist to
	// protect: PEM travels as readable text, never base64.
	PemFieldsArePlainText bool `json:"pem_fields_are_plain_text"`
}

type releaseIDCase struct {
	Ref     string `json:"ref"`
	UnixSec int64  `json:"unix_sec"`
	ID      string `json:"id"`
	Valid   bool   `json:"valid"`
}

func main() {
	out := fixtures{
		Note: "Generated by cmd/conformance. Do not edit by hand. " +
			"Regenerate with: go run ./cmd/conformance > control-plane/tests/fixtures/conformance.json",
		ProtocolVersion: protocol.Version,
		Constants: map[string]any{
			"max_frame_size":       protocol.MaxFrameSize,
			"frame_header_bytes":   4,
			"token_bytes":          enroll.TokenBytes,
			"default_token_ttl_s":  int(enroll.DefaultTokenTTL.Seconds()),
			"message_id_hex_chars": 32,
		},
	}

	// Token hashing. Fixed inputs including edge cases, so a change in either
	// implementation shows up as a failing assertion rather than as agents
	// that cannot enroll.
	for _, token := range []string{
		"",
		"a",
		"hello-world",
		"T6XxCqfGQ0pFRYxYvBtR0RhXYv0VdKJ3iNhQ8sLpYqM",
		"unicode: café 日本語 🔐",
		"with\nnewline\tand\ttabs",
	} {
		hash := enroll.HashToken(token)
		out.TokenHashes = append(out.TokenHashes, tokenHashCase{
			Token:  token,
			SHA256: fmt.Sprintf("%x", hash),
		})
	}

	// Envelope shape. Built by hand rather than via NewEnvelope so the
	// fixture is deterministic.
	envelopes := []struct {
		desc string
		env  protocol.Envelope
		body any
	}{
		{
			desc: "hello",
			env:  protocol.Envelope{V: protocol.Version, ID: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", Type: protocol.TypeHello, TS: 1793203822000},
			body: protocol.Hello{NodeID: "node-123", AgentVersion: "0.1.0", OS: "linux", Arch: "amd64", Hostname: "web-1", StartedAt: 1793203822000},
		},
		{
			desc: "hello_ack",
			env:  protocol.Envelope{V: protocol.Version, ID: "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb", ReplyTo: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", Type: protocol.TypeHelloAck, TS: 1793203822001},
			body: protocol.HelloAck{ServerVersion: "1.0.0", HeartbeatSeconds: 30},
		},
		{
			desc: "command",
			env:  protocol.Envelope{V: protocol.Version, ID: "cccccccccccccccccccccccccccccccc", Type: protocol.TypeCommand, TS: 1793203823000},
			body: protocol.Command{Kind: protocol.CommandActivateRelease, TimeoutSeconds: 600, IdempotencyKey: "deploy-42"},
		},
		{
			desc: "command_ack",
			env:  protocol.Envelope{V: protocol.Version, ID: "dddddddddddddddddddddddddddddddd", ReplyTo: "cccccccccccccccccccccccccccccccc", Type: protocol.TypeCommandAck, TS: 1793203823010},
			body: protocol.CommandAck{Accepted: true},
		},
		{
			desc: "progress",
			env:  protocol.Envelope{V: protocol.Version, ID: "eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee", ReplyTo: "cccccccccccccccccccccccccccccccc", Type: protocol.TypeProgress, TS: 1793203823100},
			body: protocol.Progress{Stream: protocol.StreamStatus, Seq: 0, Text: "create: directory /srv/app"},
		},
		{
			desc: "result",
			env:  protocol.Envelope{V: protocol.Version, ID: "ffffffffffffffffffffffffffffffff", ReplyTo: "cccccccccccccccccccccccccccccccc", Type: protocol.TypeResult, TS: 1793203824000},
			body: protocol.Result{Status: protocol.StatusSucceeded, DurationMS: 1234},
		},
		{
			desc: "error",
			env:  protocol.Envelope{V: protocol.Version, ID: "11111111111111111111111111111111", ReplyTo: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", Type: protocol.TypeError, TS: 1793203822002},
			body: protocol.Error{Code: protocol.ErrIdentityMismatch, Message: "hello node id does not match the client certificate", Fatal: true},
		},
	}

	for _, e := range envelopes {
		payload, err := json.Marshal(e.body)
		if err != nil {
			fail(err)
		}
		env := e.env
		env.Payload = payload

		encoded, err := json.Marshal(env)
		if err != nil {
			fail(err)
		}
		out.Envelopes = append(out.Envelopes, envelopeCase{Description: e.desc, JSON: encoded})
	}

	// The enrollment exchange, with real PEM in it, so a control plane in
	// another language can diff its own output against this.
	samplePEM := strings.Join([]string{
		"-----BEGIN CERTIFICATE REQUEST-----",
		"MIIBATCBqQIBADBFMQswCQYDVQQGEwJBVTETMBEGA1UE",
		"-----END CERTIFICATE REQUEST-----",
		"",
	}, "\n")

	sampleCert := strings.Join([]string{
		"-----BEGIN CERTIFICATE-----",
		"MIIBkTCCATegAwIBAgIQCgEBAwMFBwkLDQ8RExUXGTAK",
		"-----END CERTIFICATE-----",
		"",
	}, "\n")

	reqJSON, err := json.Marshal(enroll.Request{
		Token:        "T6XxCqfGQ0pFRYxYvBtR0RhXYv0VdKJ3iNhQ8sLpYqM",
		CSRPEM:       samplePEM,
		AgentVersion: "0.1.0",
		Hostname:     "web-1",
		OS:           "linux",
		Arch:         "amd64",
	})
	if err != nil {
		fail(err)
	}

	respJSON, err := json.Marshal(enroll.Response{
		NodeID:           "web-1.org-1",
		OrgID:            "org-1",
		CertPEM:          sampleCert,
		CAPEM:            sampleCert,
		ControlPlaneAddr: "cp.example:9443",
		NotAfter:         time.Date(2026, 12, 4, 0, 0, 0, 0, time.UTC),
	})
	if err != nil {
		fail(err)
	}

	out.Enrollment = enrollmentCase{
		RequestJSON:           reqJSON,
		ResponseJSON:          respJSON,
		PemFieldsArePlainText: true,
	}

	// Release ID construction, including the hostile refs a webhook can
	// deliver. The control plane builds these too, and an ID it generates
	// that the agent then rejects would fail a deploy at the last moment.
	base := time.Date(2026, 11, 4, 14, 30, 22, 0, time.UTC)
	for _, ref := range []string{
		"a1b2c3d",
		"feature/some-branch",
		"../../etc/cron.d/evil",
		"..",
		"with space",
		"",
	} {
		id := deploy.NewReleaseID(base, ref)
		out.ReleaseIDs = append(out.ReleaseIDs, releaseIDCase{
			Ref:     ref,
			UnixSec: base.Unix(),
			ID:      id,
			Valid:   deploy.ValidateReleaseID(id) == nil,
		})
	}

	for _, k := range []protocol.CommandKind{
		protocol.CommandApplyRecipe, protocol.CommandDeploy, protocol.CommandActivateRelease,
		protocol.CommandRollback, protocol.CommandExec, protocol.CommandCollectMetrics,
		protocol.CommandPruneReleases,
	} {
		out.CommandKinds = append(out.CommandKinds, string(k))
	}

	for _, t := range []protocol.Type{
		protocol.TypeHello, protocol.TypeHelloAck, protocol.TypePing, protocol.TypePong,
		protocol.TypeCommand, protocol.TypeCommandAck, protocol.TypeProgress,
		protocol.TypeResult, protocol.TypeMetrics, protocol.TypeLogBatch, protocol.TypeError,
	} {
		out.MessageTypes = append(out.MessageTypes, string(t))
	}

	for _, c := range []protocol.ErrorCode{
		protocol.ErrUnsupportedVersion, protocol.ErrIdentityMismatch, protocol.ErrMalformed,
		protocol.ErrUnknownType, protocol.ErrFrameTooLarge, protocol.ErrInternal,
	} {
		out.ErrorCodes = append(out.ErrorCodes, string(c))
	}

	for _, s := range []protocol.ResultStatus{
		protocol.StatusSucceeded, protocol.StatusFailed, protocol.StatusTimedOut, protocol.StatusCancelled,
	} {
		out.ResultStatuses = append(out.ResultStatuses, string(s))
	}

	encoder := json.NewEncoder(os.Stdout)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(out); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "conformance: %v\n", err)
	os.Exit(1)
}
